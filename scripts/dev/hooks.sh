#!/bin/sh
# Install or verify treemand's git hooks.
#
#   hooks.sh install   write the hooks (idempotent)
#   hooks.sh verify    exit 1 unless every hook below is active
#
# pre-commit         the pre-commit framework (.pre-commit-config.yaml: gitleaks,
#                    tmuxinator schema, shellcheck), installed by `pre-commit install`
# pre-commit.legacy  runs `task precommit` (gitleaks on staged changes, lint, tests);
#                    the framework's hook runs it first, before its own hooks
# pre-push           runs `task precommit` before a push to main or develop
#
# Hooks live in the repo's common git dir, so every worktree shares them.
# TREEMAND_REPO_ROOT overrides the repo (default: this checkout).

case "$0" in */*) here="${0%/*}" ;; *) here=. ;; esac
root="${TREEMAND_REPO_ROOT:-$(cd "$here/../.." && pwd)}"
cd "$root" || exit 1

marker="# treemand hook: runs task precommit"
framework="File generated by pre-commit"

hooks_dir() {
  if ! command -v git >/dev/null 2>&1; then
    echo "  inactive   git not found: install it, then run setup.sh --install" >&2
    return 1
  fi
  if [ -n "$(git config core.hooksPath)" ]; then
    echo "core.hooksPath is set; the pre-commit framework will not install. Unset it: git config --unset-all core.hooksPath" >&2
    return 1
  fi
  d="$(git rev-parse --git-path hooks)" || return 1
  case "$d" in /*) ;; *) d="$root/$d" ;; esac
  echo "$d"
}

write_pre_commit() {
  cat >"$1" <<EOF
#!/bin/sh
$marker
# Installed by scripts/dev/hooks.sh (task setup -- --install).
if ! command -v task >/dev/null 2>&1; then
  echo "task not found: skipping task precommit (install go-task)" >&2
  exit 0
fi
echo "Running precommit checks (task precommit)..."
task precommit
EOF
  chmod +x "$1"
}

write_pre_push() {
  cat >"$1" <<EOF
#!/bin/sh
$marker
# Installed by scripts/dev/hooks.sh (task setup -- --install).
# Runs task precommit before a push to main or develop.
run=0
while read -r _ _ remote_ref _; do
  case "\$remote_ref" in refs/heads/main | refs/heads/develop) run=1 ;; esac
done
[ "\$run" = 1 ] || exit 0
if ! command -v task >/dev/null 2>&1; then
  echo "task not found: skipping pre-push checks (install go-task)" >&2
  exit 0
fi
echo "Running precommit checks before push..."
task precommit
EOF
  chmod +x "$1"
}

ours() { [ -f "$1" ] && grep -q "task precommit" "$1"; }
is_framework() { [ -f "$1" ] && grep -q "$framework" "$1"; }

install() {
  d="$(hooks_dir)" || return 1
  mkdir -p "$d"
  write_pre_push "$d/pre-push"
  echo "  installed pre-push"
  if ! command -v pre-commit >/dev/null 2>&1; then
    write_pre_commit "$d/pre-commit"
    echo "  installed pre-commit (task precommit only: install pre-commit for the framework hooks)"
    return 1
  fi
  if [ -e "$d/pre-commit" ] && ! is_framework "$d/pre-commit"; then
    if ours "$d/pre-commit"; then
      rm -f "$d/pre-commit"
    else
      mv "$d/pre-commit" "$d/pre-commit.bak"
      echo "  kept your existing pre-commit hook as pre-commit.bak"
    fi
  fi
  write_pre_commit "$d/pre-commit.legacy"
  pre-commit install >/dev/null || return 1
  echo "  installed pre-commit (framework) chaining pre-commit.legacy (task precommit)"
}

verify() {
  d="$(hooks_dir)" || return 1
  ok=0
  line() { printf '  %-10s %-18s %s\n' "$1" "$2" "$3"; }
  if [ -x "$d/pre-commit" ] && is_framework "$d/pre-commit"; then
    line ok pre-commit "pre-commit framework (.pre-commit-config.yaml)"
  else
    line inactive pre-commit "pre-commit framework hook not installed"; ok=1
  fi
  if [ -x "$d/pre-commit.legacy" ] && ours "$d/pre-commit.legacy"; then
    line ok pre-commit.legacy "task precommit, run by the framework hook"
  else
    line inactive pre-commit.legacy "task precommit hook not installed"; ok=1
  fi
  if [ -x "$d/pre-push" ] && ours "$d/pre-push"; then
    line ok pre-push "task precommit before pushes to main"
  else
    line inactive pre-push "task precommit pre-push hook not installed"; ok=1
  fi
  if [ "$ok" = 1 ]; then echo "  hooks inactive: run sh scripts/dev/setup.sh --install (task setup -- --install)"; fi
  return "$ok"
}

case "${1:-}" in
  install) install ;;
  verify) verify ;;
  *) echo "usage: hooks.sh install|verify" >&2; exit 2 ;;
esac
