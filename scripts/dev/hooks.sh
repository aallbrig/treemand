#!/bin/sh
# Install or verify treemand's git hooks.
#
#   hooks.sh install   write the hooks (idempotent)
#   hooks.sh verify    exit 1 unless every hook below is active
#
# pre-commit         the pre-commit framework (.pre-commit-config.yaml: tmuxinator
#                    schema), installed by `pre-commit install`
# pre-commit.legacy  runs `task precommit` (precommit.sh: gitleaks, and lint scoped
#                    to the staged Go, shell and infra/ files); the framework's hook
#                    runs it first, before its own hooks
# commit-msg         commit_msg.sh: subject length, required trailers
# pre-push           prepush.sh on every branch: task measure:gate, coverage:check
#                    and test-race, skipping a step task ci already proved for
#                    the pushed tree (proof.sh)
#
# A hook fails when go-task is missing: a missing tool never turns a gate off.
# Hooks live in the repo's common git dir, so every worktree shares them.
# TREEMAND_REPO_ROOT overrides the repo (default: this checkout).

case "$0" in */*) here="${0%/*}" ;; *) here=. ;; esac
root="${TREEMAND_REPO_ROOT:-$(cd "$here/../.." && pwd)}"
cd "$root" || exit 1

marker="# treemand hook (scripts/dev/hooks.sh)"
missing_task='  echo "task not found: install go-task (sh scripts/dev/setup.sh --install)" >&2'
framework="File generated by pre-commit"

hooks_dir() {
  if ! command -v git >/dev/null 2>&1; then
    echo "  inactive   git not found: install it, then run setup.sh --install" >&2
    return 1
  fi
  if [ -n "$(git config core.hooksPath)" ]; then
    echo "core.hooksPath is set; the pre-commit framework will not install. Unset it: git config --unset-all core.hooksPath" >&2
    return 1
  fi
  d="$(git rev-parse --git-path hooks)" || return 1
  case "$d" in /*) ;; *) d="$root/$d" ;; esac
  echo "$d"
}

write_pre_commit() {
  cat >"$1" <<EOF
#!/bin/sh
$marker
# Installed by scripts/dev/hooks.sh (task setup -- --install).
if ! command -v task >/dev/null 2>&1; then
$missing_task
  exit 1
fi
task precommit
EOF
  chmod +x "$1"
}

write_pre_push() {
  cat >"$1" <<EOF
#!/bin/sh
$marker
# Installed by scripts/dev/hooks.sh (task setup -- --install).
# Runs scripts/dev/prepush.sh on every branch: task measure:gate, coverage:check
# and test-race, skipping a step task ci already proved for the pushed tree.
if ! command -v task >/dev/null 2>&1; then
$missing_task
  exit 1
fi
if [ ! -f scripts/dev/prepush.sh ]; then
  echo "pre-push: this branch predates scripts/dev/prepush.sh; running task measure:gate"
  exec task measure:gate
fi
exec sh scripts/dev/prepush.sh "\$@"
EOF
  chmod +x "$1"
}

write_commit_msg() {
  cat >"$1" <<EOF
#!/bin/sh
$marker
# Installed by scripts/dev/hooks.sh (task setup -- --install).
# Runs scripts/dev/commit_msg.sh: subject length and required trailers.
if [ ! -f scripts/dev/commit_msg.sh ]; then
  echo "commit-msg: this branch predates scripts/dev/commit_msg.sh; not checked"
  exit 0
fi
exec sh scripts/dev/commit_msg.sh "\$1"
EOF
  chmod +x "$1"
}

ours() { [ -f "$1" ] && grep -q "# treemand hook" "$1"; }

# Keep a hook someone wrote by hand as <name>.bak before writing ours.
keep_custom() {
  if [ -e "$1" ] && ! ours "$1" && ! is_framework "$1"; then
    mv "$1" "$1.bak"
    echo "  kept your existing ${1##*/} hook as ${1##*/}.bak"
  fi
}
is_framework() { [ -f "$1" ] && grep -q "$framework" "$1"; }

install() {
  d="$(hooks_dir)" || return 1
  mkdir -p "$d"
  keep_custom "$d/pre-push"
  write_pre_push "$d/pre-push"
  echo "  installed pre-push"
  keep_custom "$d/commit-msg"
  write_commit_msg "$d/commit-msg"
  echo "  installed commit-msg"
  if ! command -v pre-commit >/dev/null 2>&1; then
    write_pre_commit "$d/pre-commit"
    echo "  installed pre-commit (task precommit only: install pre-commit for the framework hooks)"
    return 1
  fi
  if [ -e "$d/pre-commit" ] && ! is_framework "$d/pre-commit"; then
    if ours "$d/pre-commit"; then
      rm -f "$d/pre-commit"
    else
      mv "$d/pre-commit" "$d/pre-commit.bak"
      echo "  kept your existing pre-commit hook as pre-commit.bak"
    fi
  fi
  write_pre_commit "$d/pre-commit.legacy"
  pre-commit install >/dev/null || return 1
  echo "  installed pre-commit (framework) chaining pre-commit.legacy (task precommit)"
}

verify() {
  d="$(hooks_dir)" || return 1
  ok=0
  line() { printf '  %-10s %-18s %s\n' "$1" "$2" "$3"; }
  if [ -x "$d/pre-commit" ] && is_framework "$d/pre-commit"; then
    line ok pre-commit "pre-commit framework (.pre-commit-config.yaml)"
  else
    line inactive pre-commit "pre-commit framework hook not installed"; ok=1
  fi
  if [ -x "$d/pre-commit.legacy" ] && ours "$d/pre-commit.legacy"; then
    line ok pre-commit.legacy "task precommit (staged-scoped), run by the framework hook"
  else
    line inactive pre-commit.legacy "task precommit hook not installed"; ok=1
  fi
  if [ -x "$d/commit-msg" ] && ours "$d/commit-msg"; then
    line ok commit-msg "subject length and required trailers"
  else
    line inactive commit-msg "commit-msg hook not installed"; ok=1
  fi
  if [ -x "$d/pre-push" ] && grep -q prepush.sh "$d/pre-push"; then
    line ok pre-push "gate, coverage and race tests on every branch, unless task ci proved the tree"
  else
    line inactive pre-push "pre-push hook missing or out of date"; ok=1
  fi
  if [ "$ok" = 1 ]; then echo "  hooks inactive: run sh scripts/dev/setup.sh --install (task setup -- --install)"; fi
  return "$ok"
}

case "${1:-}" in
  install) install ;;
  verify) verify ;;
  *) echo "usage: hooks.sh install|verify" >&2; exit 2 ;;
esac
