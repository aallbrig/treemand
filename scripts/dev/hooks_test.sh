#!/bin/sh
# shellcheck disable=SC2016,SC2329
# Behaviour tests for scripts/dev/hooks.sh against throwaway git repos. `task`
# is a stub that records its arguments, so a real commit proves the hook chain:
# git -> pre-commit framework -> pre-commit.legacy -> task precommit.
# The framework cases are skipped when pre-commit is not installed.
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT INT TERM
fail=0
check() { if ! eval "$2"; then echo "hooks_test FAIL: $1" >&2; fail=1; fi; }

sh_bin="$(command -v dash || command -v sh)"
mkdir -p "$tmp/bin"
printf '#!/bin/sh\necho "task $*" >>"%s/task-calls"\n' "$tmp" >"$tmp/bin/task"
chmod +x "$tmp/bin/task"
export PATH="$tmp/bin:$PATH" PRE_COMMIT_HOME="$tmp/pre-commit-home"
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
unset CLAUDECODE

newrepo() {
  rm -rf "$tmp/repo" "$tmp/wt" "$tmp/task-calls"
  git init -q "$tmp/repo"
  git -C "$tmp/repo" config user.email dev@example.com
  git -C "$tmp/repo" config user.name dev
  printf 'repos: []\n' >"$tmp/repo/.pre-commit-config.yaml"
  git -C "$tmp/repo" add .pre-commit-config.yaml
  git -C "$tmp/repo" commit -q --no-verify -m init
}
hooks() { (cd "$1" && TREEMAND_REPO_ROOT="$1" "$sh_bin" "$here/hooks.sh" "$2") >"$tmp/out" 2>&1; echo $? >"$tmp/rc"; }
rc() { cat "$tmp/rc"; }
h="$tmp/repo/.git/hooks"

newrepo
hooks "$tmp/repo" verify
check "verify fails before install" '[ "$(rc)" = 1 ]'
check "verify names the fix" 'grep -q "task setup" "$tmp/out"'

hooks "$tmp/repo" bogus
check "unknown command exits 2" '[ "$(rc)" = 2 ]'

if command -v pre-commit >/dev/null 2>&1; then
  hooks "$tmp/repo" install
  check "install exits 0" '[ "$(rc)" = 0 ]'
  check "framework hook installed" 'grep -q "File generated by pre-commit" "$h/pre-commit"'
  check "legacy hook runs task precommit" 'grep -q "task precommit" "$h/pre-commit.legacy" && [ -x "$h/pre-commit.legacy" ]'
  check "pre-push installed" 'grep -q "prepush.sh" "$h/pre-push" && [ -x "$h/pre-push" ]'
  hooks "$tmp/repo" verify
  check "verify passes after install" '[ "$(rc)" = 0 ]'

  git -C "$tmp/repo" commit -q --allow-empty -m chained >/dev/null 2>&1
  check "a commit runs task precommit through the framework" 'grep -qx "task precommit" "$tmp/task-calls"'

  hooks "$tmp/repo" install
  check "reinstall is idempotent" '[ "$(rc)" = 0 ] && [ ! -e "$h/pre-commit.bak" ]'
  hooks "$tmp/repo" verify
  check "verify passes after reinstall" '[ "$(rc)" = 0 ]'

  git -C "$tmp/repo" worktree add -q "$tmp/wt" >/dev/null 2>&1
  hooks "$tmp/wt" verify
  check "a worktree shares the hooks" '[ "$(rc)" = 0 ]'

  # A hook someone wrote by hand is kept, not overwritten.
  newrepo
  printf '#!/bin/sh\necho mine\n' >"$h/pre-commit"
  chmod +x "$h/pre-commit"
  hooks "$tmp/repo" install
  check "custom hook backed up" 'grep -q "echo mine" "$h/pre-commit.bak"'
  check "custom hook replaced by the chain" 'grep -q "task precommit" "$h/pre-commit.legacy"'

  # Only the legacy hook present (framework missing): verify fails.
  rm -f "$h/pre-commit"
  hooks "$tmp/repo" verify
  check "missing framework hook fails verify" '[ "$(rc)" = 1 ]'
else
  echo "hooks_test: pre-commit not installed; skipping the framework cases"
fi

# The hooks run the repo's own scripts, so the test repo carries them.
withscripts() {
  mkdir -p "$tmp/repo/scripts/dev"
  for s in precommit prepush commit_msg proof; do cp "$here/$s.sh" "$tmp/repo/scripts/dev/"; done
  git -C "$tmp/repo" add scripts
  git -C "$tmp/repo" commit -q --no-verify -m scripts
}
calls() { cat "$tmp/task-calls" "$tmp/tool-calls" 2>/dev/null; }
stub() { printf '#!/bin/sh\necho "%s $*" >>"%s/tool-calls"\n' "$1" "$tmp" >"$tmp/bin/$1"; chmod +x "$tmp/bin/$1"; }
for t in go golangci-lint shellcheck; do stub "$t"; done

# pre-push runs on every branch: the ratchets, coverage floors and race tests
# (#473), unless task ci already proved the pushed tree.
newrepo
withscripts
hooks "$tmp/repo" install
check "pre-push runs prepush.sh" 'grep -q "scripts/dev/prepush.sh" "$h/pre-push" && [ -x "$h/pre-push" ]'
check "commit-msg installed" 'grep -q "commit_msg.sh" "$h/commit-msg" && [ -x "$h/commit-msg" ]'
head="$(git -C "$tmp/repo" rev-parse HEAD)"
prepush() {
  rm -f "$tmp/task-calls"
  (cd "$tmp/repo" && printf 'refs/heads/x %s %s 0000000000000000000000000000000000000000\n' "${2:-$head}" "$1" | "$h/pre-push" origin url) >"$tmp/out" 2>&1
  echo $? >"$tmp/rc"
}
all3='grep -qx "task measure:gate" "$tmp/task-calls" && grep -qx "task coverage:check" "$tmp/task-calls" && grep -qx "task test-race" "$tmp/task-calls"'
prepush refs/heads/feature
check "a branch push runs the gate, coverage and race tests" "[ \"\$(rc)\" = 0 ] && $all3"
prepush refs/heads/feature 0000000000000000000000000000000000000000
check "deleting a remote branch runs nothing" '[ "$(rc)" = 0 ] && [ ! -e "$tmp/task-calls" ]'

# A pass stamps the tree, so the same tree pushed again runs nothing.
prepush refs/heads/other
check "a proven tree skips every step" '[ "$(rc)" = 0 ] && [ ! -e "$tmp/task-calls" ] && grep -q "already proven" "$tmp/out"'

# task ci stamps the tree it passed on; a dirty tree is not stamped.
newrepo
withscripts
hooks "$tmp/repo" install
head="$(git -C "$tmp/repo" rev-parse HEAD)"
echo dirty >"$tmp/repo/scripts/x"
(cd "$tmp/repo" && sh scripts/dev/proof.sh stamp coverage:check measure:gate test-race) >"$tmp/out" 2>&1
check "a dirty tree is not stamped" 'grep -q "not stamping" "$tmp/out"'
rm -f "$tmp/repo/scripts/x"
(cd "$tmp/repo" && sh scripts/dev/proof.sh stamp coverage:check measure:gate) >/dev/null 2>&1
prepush refs/heads/feature
check "steps task ci proved are skipped, the rest run" '[ "$(rc)" = 0 ] && grep -qx "task test-race" "$tmp/task-calls" && ! grep -q "task coverage:check\|task measure:gate" "$tmp/task-calls"'
git -C "$tmp/repo" commit -q --no-verify --allow-empty -m next
echo next >"$tmp/repo/new"
git -C "$tmp/repo" add new
git -C "$tmp/repo" commit -q --no-verify -m changed
prepush refs/heads/feature "$(git -C "$tmp/repo" rev-parse HEAD)"
check "a new tree runs every step" "$all3"

printf '#!/bin/sh\necho "task $*" >>"%s/task-calls"\n[ "$1" != coverage:check ]\n' "$tmp" >"$tmp/bin/task"
echo again >"$tmp/repo/new"
git -C "$tmp/repo" commit -q --no-verify -am again
prepush refs/heads/feature "$(git -C "$tmp/repo" rev-parse HEAD)"
check "a failing step blocks the push" '[ "$(rc)" = 1 ] && ! grep -qx "task test-race" "$tmp/task-calls"'
printf '#!/bin/sh\necho "task $*" >>"%s/task-calls"\n' "$tmp" >"$tmp/bin/task"

# A missing task fails the hook instead of skipping the gate.
nopath="$tmp/notask"
mkdir -p "$nopath"
for t in git sh dash cat grep sed awk head wc tr find mkdir rm printf; do
  p="$(command -v "$t" 2>/dev/null)" && ln -sf "$p" "$nopath/$t"
done
(cd "$tmp/repo" && echo "refs/heads/x $(git rev-parse HEAD) refs/heads/y 0" | PATH="$nopath" sh "$h/pre-push" origin url; echo "rc=$?") >"$tmp/out" 2>&1
check "pre-push fails without task, with the install hint" 'grep -q "rc=1" "$tmp/out" && grep -q "install go-task" "$tmp/out"'
legacy="$h/pre-commit.legacy"; [ -f "$legacy" ] || legacy="$h/pre-commit"
(cd "$tmp/repo" && PATH="$nopath" sh "$legacy"; echo "rc=$?") >"$tmp/out" 2>&1
check "pre-commit fails without task, with the install hint" 'grep -q "rc=1" "$tmp/out" && grep -q "install go-task" "$tmp/out"'

# pre-commit is scoped to what is staged.
precommit() {
  rm -f "$tmp/task-calls" "$tmp/tool-calls"
  (cd "$tmp/repo" && sh scripts/dev/precommit.sh) >"$tmp/out" 2>&1
  echo $? >"$tmp/rc"
}
newrepo
withscripts
hooks "$tmp/repo" install
mkdir -p "$tmp/repo/docs" "$tmp/repo/cli/treemand/tui" "$tmp/repo/cli/treemand/cmd" "$tmp/repo/infra"
echo notes >"$tmp/repo/docs/a.md"
git -C "$tmp/repo" add docs
precommit
check "a docs-only commit runs gitleaks and nothing else" '[ "$(rc)" = 0 ] && [ "$(calls)" = "task secrets" ]'
git -C "$tmp/repo" commit -q --no-verify -m docs

printf 'package tui\n' >"$tmp/repo/cli/treemand/tui/a.go"
printf 'package cmd\n' >"$tmp/repo/cli/treemand/cmd/b.go"
git -C "$tmp/repo" add cli/treemand/tui
precommit
check "staged Go lints only its package" '[ "$(rc)" = 0 ] && grep -qx "go vet ./cli/treemand/tui" "$tmp/tool-calls" && grep -qx "golangci-lint run ./cli/treemand/tui" "$tmp/tool-calls" && ! grep -q cmd "$tmp/tool-calls"'
check "staged Go skips infra lint" '! grep -q infra "$tmp/task-calls"'
printf 'package tui\nfunc  x() {}\n' >"$tmp/repo/cli/treemand/tui/a.go"
git -C "$tmp/repo" add cli/treemand/tui
precommit
check "unformatted staged Go fails" '[ "$(rc)" = 1 ] && grep -q "needs gofmt" "$tmp/out"'
git -C "$tmp/repo" reset -q

printf '#!/bin/sh\necho hi\n' >"$tmp/repo/scripts/p.sh"
printf '#!/usr/bin/env bash\necho hi\n' >"$tmp/repo/scripts/b.sh"
git -C "$tmp/repo" add scripts/p.sh scripts/b.sh
precommit
check "staged shell is shellchecked by its shell" 'grep -qx "shellcheck -x --shell=sh -S warning scripts/p.sh" "$tmp/tool-calls" && grep -qx "shellcheck -x -S warning scripts/b.sh" "$tmp/tool-calls"'
check "staged shell skips Go" '! grep -q "^go \|golangci" "$tmp/tool-calls"'
git -C "$tmp/repo" reset -q

echo "Resources: {}" >"$tmp/repo/infra/site.yaml"
git -C "$tmp/repo" add infra
precommit
check "staged infra/ runs infra lint" 'grep -qx "task infra:lint" "$tmp/task-calls"'
git -C "$tmp/repo" reset -q

printf '#!/bin/sh\necho "task $*" >>"%s/task-calls"\n[ "$1" != secrets ]\n' "$tmp" >"$tmp/bin/task"
git -C "$tmp/repo" add docs 2>/dev/null; echo more >>"$tmp/repo/docs/a.md"; git -C "$tmp/repo" add docs
precommit
check "a gitleaks finding fails the commit" '[ "$(rc)" = 1 ]'
printf '#!/bin/sh\necho "task $*" >>"%s/task-calls"\n' "$tmp" >"$tmp/bin/task"

# commit-msg: subject length and required trailers.
msg() { printf '%b' "$1" >"$tmp/msg"; (cd "$tmp/repo" && env CLAUDECODE="${2:-}" "$h/commit-msg" "$tmp/msg") >"$tmp/out" 2>&1; echo $? >"$tmp/rc"; }
long="$(printf '%073d' 0)"
msg "Fix the thing\n\nBody.\n"
check "a short subject passes" '[ "$(rc)" = 0 ]'
msg "$long\n"
check "a 73-character subject fails" '[ "$(rc)" = 1 ] && grep -q "73 characters" "$tmp/out"'
msg "$(printf '%072d' 0)\n# a comment line longer than seventy-two characters is not part of the message at all\n"
check "72 characters pass; comments are ignored" '[ "$(rc)" = 0 ]'
msg "Subject\nbody straight after\n"
check "a missing blank line fails" '[ "$(rc)" = 1 ]'
msg "Merge branch $long\n"
check "merge subjects are exempt" '[ "$(rc)" = 0 ]'
msg "Fix it\n" 1
check "an agent commit without Co-Authored-By fails" '[ "$(rc)" = 1 ] && grep -q Co-Authored-By "$tmp/out"'
msg "Fix it\n\nCo-Authored-By: Agent <agent@example.com>\n" 1
check "an agent commit with Co-Authored-By passes" '[ "$(rc)" = 0 ]'
msg "Revert \"x\"\n\nThis reverts commit abc.\n" 1
check "git revert messages are exempt" '[ "$(rc)" = 0 ]'
(cd "$tmp/repo" && CLAUDECODE='' git commit -q --allow-empty -m "$long") >/dev/null 2>&1
check "a real commit with a long subject is refused" '[ "$(git -C "$tmp/repo" log -1 --format=%s)" != "$long" ]'

[ "$fail" = 0 ] && echo "hooks_test: ok"
exit "$fail"
